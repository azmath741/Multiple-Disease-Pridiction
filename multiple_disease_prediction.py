import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder
from tensorflow import keras
from tensorflow.keras import layers

"""step 2:
 Generateing the  synthetic healthcare dataset with multiple diseases

"""

#creating a funciton to generate data
def generate_synthetic_data():
  np.random.seed(42)
  num_samples = 4000
  data={
        "age":np.random.randint(18,90,num_samples),
        "gender":np.random.choice(["Male","Female"],num_samples),
        "bmi": np.round(np.random.uniform(18, 40, num_samples), 1),
        "blood_pressure": np.random.randint(90, 180, num_samples),
        "cholesterol": np.random.randint(100, 300, num_samples),
        "glucose": np.random.randint(70, 200, num_samples),
        "smoking": np.random.choice([0, 1], num_samples),
        "exercise": np.random.choice([0, 1], num_samples),
        "heart_disease": np.random.choice([0, 1], num_samples, p=[0.85, 0.15]),
        "diabetes": np.random.choice([0, 1], num_samples, p=[0.80, 0.20]),
        "hypertension": np.random.choice([0, 1], num_samples, p=[0.70, 0.30]),
        "stroke": np.random.choice([0, 1], num_samples, p=[0.90, 0.10]),
  }
  return  pd.DataFrame(data)

"""Step 3:
Preprocess data
"""

def preprocess_data(df):
    encoder = LabelEncoder()
    df['gender'] = encoder.fit_transform(df['gender'])
    X = df.drop(columns=['heart_disease', 'diabetes', 'hypertension', 'stroke'])
    y = df[['heart_disease', 'diabetes', 'hypertension', 'stroke']]
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)
    return train_test_split(X_scaled, y, test_size=0.2, random_state=42)

"""Step 4: Training the  model"""

def train_model(X_train, y_train):
    model = keras.Sequential([
        layers.Dense(32, activation='relu', input_shape=(X_train.shape[1],)),
        layers.Dense(32, activation='relu'),
        layers.Dense(4, activation='sigmoid')# Output for four diseases
         ])
    model.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
    model.fit(X_train, y_train, epochs=50, batch_size=32, verbose=0)
    return model

"""Step 5: Make predictions"""

def make_predictions(model, input_data):
    input_data = np.array(input_data).reshape(1, -1)
    prediction = model.predict(input_data)
    return prediction

"""Step 6: Asking Input for user"""

def get_user_input():
    print("Please provide the following details:")
    age = int(input("Age: "))
    gender = input("Gender (Male/Female): ")
    bmi = float(input("BMI: "))
    blood_pressure = int(input("Blood Pressure: "))
    cholesterol = int(input("Cholesterol: "))
    glucose = int(input("Glucose: "))
    smoking = int(input("Smoking (0: No, 1: Yes): "))
    exercise = int(input("Exercise (0: No, 1: Yes): "))

    gender_encoded = 1 if gender.lower() == "male" else 0
    return [age, gender_encoded, bmi, blood_pressure, cholesterol, glucose, smoking, exercise]

# Main execution
if __name__ == "__main__":
    # Generate and preprocess data
    data = generate_synthetic_data()
    X_train, X_test, y_train, y_test = preprocess_data(data)

    # Train model
    model = train_model(X_train, y_train)

    # Get user input
    user_data = get_user_input()

    # Make predictions
    predictions = make_predictions(model, user_data)
    print("Predictions (Heart Disease, Diabetes, Hypertension, Stroke):")
    print(predictions)